    #[test]
    fn shift_image_positive_shifts_right() {
        // 4x1 image: [R, G, B, W]
        let mut img = RgbaImage::new(4, 1);
        img.put_pixel(0, 0, Rgba([255, 0, 0, 255]));   // R
        img.put_pixel(1, 0, Rgba([0, 255, 0, 255]));   // G
        img.put_pixel(2, 0, Rgba([0, 0, 255, 255]));   // B
        img.put_pixel(3, 0, Rgba([255, 255, 255, 255]));// W
        let dyn_img = DynamicImage::ImageRgba8(img);

        // Shift right by 1: result should be [transparent, R, G, B]
        let shifted = shift_image_horizontal(&dyn_img, 1);
        let out = shifted.to_rgba8();

        // x=0 should be transparent
        assert_eq!(out.get_pixel(0, 0)[3], 0);
        // x=1 should be R
        assert_eq!(*out.get_pixel(1, 0), Rgba([255, 0, 0, 255]));
        // x=2 should be G
        assert_eq!(*out.get_pixel(2, 0), Rgba([0, 255, 0, 255]));
        // x=3 should be B
        assert_eq!(*out.get_pixel(3, 0), Rgba([0, 0, 255, 255]));
    }

