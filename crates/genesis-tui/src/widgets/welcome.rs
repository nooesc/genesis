    #[test]
    fn next_frame_cycles() {
        let widget_info = WelcomeInfo {
            model: "test".to_string(),
            cwd: "/tmp".to_string(),
            version: "0.0.0".to_string(),
        };
        let mut widget = WelcomeWidget::new(widget_info, &[], &[]);

        // Widget should be animated since the embedded images are available.
        assert!(widget.animated);
        assert_eq!(widget.current_frame, 0);

        // Advance through all 8 frames and verify wrap-around.
        for expected in 1..=8 {
            widget.next_frame();
            assert_eq!(widget.current_frame, expected % 8);
        }
        // After 8 advances we should be back at 0.
        assert_eq!(widget.current_frame, 0);
    }
