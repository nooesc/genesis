function createStorageMock(): Storage {
  const store = new Map<string, string>()

  return {
    get length() {
      return store.size
    },
    clear() {
      store.clear()
    },
    getItem(key) {
      return store.get(key) ?? null
    },
    key(index) {
      return [...store.keys()][index] ?? null
    },
    removeItem(key) {
      store.delete(key)
    },
    setItem(key, value) {
      store.set(key, value)
    },
  }
}

export function installStorageMock(): Storage {
  const storage = createStorageMock()

  Object.defineProperty(globalThis, 'localStorage', {
    value: storage,
    configurable: true,
  })

  return storage
}
